"""Константы, общие для нескольких слоёв приложения.

Модуль намеренно не импортирует ничего из проекта: его может использовать
любой слой, не рискуя кольцевым импортом.

Здесь лежит то, что не настраивается через окружение, — либо потому что
задано стандартом (длины реквизитов по ГОСТ Р 56042-2014), либо потому что
это значение по умолчанию, от которого отталкиваются настройки.
"""

# ---- Длины полей: реквизиты получателя (ГОСТ Р 56042-2014) -------------
# Одни и те же значения нужны в колонках базы, в схемах запроса и в
# описании HTTP-параметров. Держать их в одном месте обязательно: иначе
# поле, которое примет база, отвергнет схема, и наоборот.

NAME_MAX_LENGTH = 160
"""Наименование получателя платежа и любое ФИО."""

BANK_NAME_MAX_LENGTH = 45
PURPOSE_MAX_LENGTH = 210
PHONE_MAX_LENGTH = 25

ACCOUNT_LENGTH = 20
"""Расчётный и корреспондентский счёт — ровно 20 цифр."""

BIC_LENGTH = 9
KPP_LENGTH = 9

INN_LENGTHS = (10, 12)
"""10 цифр у юридического лица, 12 — у ИП и физлица."""

MAX_SUM_KOPECKS = 99_999_999_999
"""Потолок суммы платежа — около миллиарда рублей."""

# ---- Длины собственных полей сервиса -----------------------------------
EMAIL_MAX_LENGTH = 320
"""Предел по RFC 5321: 64 символа до собаки плюс 255 после."""

ALIAS_MAX_LENGTH = 64
TOKEN_LABEL_MAX_LENGTH = 80
DISPLAY_NAME_MAX_LENGTH = 160
PASSWORD_HASH_MAX_LENGTH = 255

SHA256_HEX_LENGTH = 64
"""Длина шестнадцатеричной записи SHA-256 — ключи и идемпотентность."""

TOKEN_PREFIX_LENGTH = 8
"""Сколько первых символов ключа API показывается заказчику открыто.

По ним он узнаёт нужный ключ в списке, но восстановить остальное нельзя.
"""

STORAGE_KEY_MAX_LENGTH = 255
"""Ключ файла в объектном хранилище."""

PUBLIC_TOKEN_MAX_LENGTH = 32
"""Публичный идентификатор счёта для ссылок вида /pay/{token}."""

QR_COLOR_LENGTH = 7
"""Цвет в формате #RRGGBB."""

# ---- Регулярные выражения, собранные из длин выше -----------------------
ACCOUNT_PATTERN = rf"^\d{{{ACCOUNT_LENGTH}}}$"
BIC_PATTERN = rf"^\d{{{BIC_LENGTH}}}$"
KPP_PATTERN = rf"^\d{{{KPP_LENGTH}}}$"
INN_PATTERN = "|".join(rf"^\d{{{length}}}$" for length in INN_LENGTHS)

# ---- Значения по умолчанию для отрисовки QR ----------------------------
# От них отталкиваются и настройки, и сигнатура функции отрисовки:
# так у значения ровно один источник.

DEFAULT_QR_COLOR = "#000000"
DEFAULT_QR_SCALE = 10
"""Сколько пикселей занимает один модуль кода."""

DEFAULT_QR_BORDER = 4
"""Ширина белого поля вокруг кода в модулях.

Меньше четырёх ставить нельзя: сканеры используют это поле, чтобы найти
код на странице.
"""

# ---- Комиссия эквайринга ------------------------------------------------
BASIS_POINTS_PER_PERCENT = 100
"""Базисных пунктов в одном проценте."""

BASIS_POINTS_TOTAL = 10_000
"""Базисных пунктов в единице. Ставка хранится целым числом пунктов:
0,7 % — это 70. Дробей и чисел с плавающей точкой в деньгах нет нигде.
"""

MAX_ACQUIRING_FEE_BPS = 10_000
"""Потолок ставки — 100 %. Больше физически быть не может."""

DEFAULT_ACQUIRING_FEE_BPS = 70
"""Ставка по умолчанию — 0,7 %. От неё отталкивается настройка сервиса."""

# ---- Админка ------------------------------------------------------------
ADMIN_SESSION_TOKEN_BYTES = 32
CSRF_TOKEN_BYTES = 32
TOTP_SECRET_LENGTH = 32
"""Длина секрета TOTP в символах base32."""

IP_ADDRESS_MAX_LENGTH = 45
"""IPv6 в текстовом виде занимает до 45 символов."""

USER_AGENT_MAX_LENGTH = 1000
"""Обрезка строки браузера: полная бывает абсурдно длинной."""

# ---- Единицы времени ----------------------------------------------------
SECONDS_PER_DAY = 24 * 60 * 60
