"""Абстракция объектного хранилища.

В хранилище лежат логотипы организаций. Готовые QR-коды там не лежат
и лежать не должны: повторный запрос приносит те же параметры, поэтому
картинку дешевле нарисовать заново, чем хранить десятки тысяч файлов
в сутки и потом их вычищать.

Протокол вынесен отдельно, чтобы тесты работали с хранилищем в памяти,
а прод — с S3, и код между ними не отличался ни строкой.
"""

from typing import Protocol


class Storage(Protocol):
    """Минимальный интерфейс хранилища файлов."""

    async def put(self, key: str, data: bytes, *, content_type: str) -> None:
        """Кладёт файл. Существующий файл с тем же ключом перезаписывается."""
        ...

    async def get(self, key: str) -> bytes | None:
        """Отдаёт файл или None, если его нет."""
        ...

    async def delete(self, key: str) -> None:
        """Удаляет файл. Отсутствие файла ошибкой не считается."""
        ...
