"""Вычисление ключа идемпотентности счёта.

Это сердце тарификации. Заказчик платит не за обращение к API, а за счёт:
первый запрос с новым набором параметров создаёт счёт и списывает рубль,
любой повтор с теми же параметрами в течение бесплатного периода
не стоит ничего.

Без этого механизма предзагрузка картинок почтовыми клиентами
тарифицировалась бы как новые счета, и заказчик, отправивший 60 счетов,
увидел бы в выписке списание за 300 обращений.
"""

import hashlib
import uuid

from nosbp.payments.schemas import PaymentRequest

VERSION = "v1"
"""Версия схемы ключа.

Входит в хэш: если правила нормализации когда-нибудь изменятся, старые
и новые ключи не станут случайно совпадать.
"""

FIELD_SEPARATOR = "\x1f"
"""Разделитель полей — символ, который не встречается в пользовательском вводе.

Обычный дефис или двоеточие позволили бы подобрать разные наборы
параметров с одинаковым ключом.
"""


def _normalize(value: str | None) -> str:
    """Приводит значение к каноническому виду.

    Регистр сохраняется: «Оплата заказа» и «ОПЛАТА ЗАКАЗА» — это разные
    назначения платежа, и заказчик вправе выставить оба. А вот лишние
    пробелы и переводы строк смысла не несут и схлопываются, иначе
    случайный пробел в шаблоне CRM превратил бы повтор в новый счёт.
    """
    if value is None:
        return ""
    return " ".join(value.split())


def build_idempotency_key(
    *,
    organization_id: uuid.UUID,
    payment: PaymentRequest,
) -> str:
    """Считает ключ идемпотентности для набора параметров.

    Персональные данные плательщика участвуют в вычислении, но остаются
    только внутри хэша: восстановить из ключа фамилию или телефон нельзя,
    а два запроса на разных плательщиков корректно считаются разными
    счетами.

    :return: шестнадцатеричная строка SHA-256 длиной 64 символа.
    """
    parts = (
        VERSION,
        str(organization_id),
        "" if payment.sum_kopecks is None else str(payment.sum_kopecks),
        _normalize(payment.purpose),
        _normalize(payment.payer.last_name),
        _normalize(payment.payer.first_name),
        _normalize(payment.payer.middle_name),
        _normalize(payment.payer.phone),
    )
    raw = FIELD_SEPARATOR.join(parts).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()
