"""Письмо и способ его доставки.

Содержимое письма отделено от способа отправки: :class:`Letter` описывает,
что человек прочитает, а :class:`MailSender` — как это до него доедет.
Благодаря такому разделению тесты проверяют тексты писем, не поднимая
почтовый сервер.
"""

from dataclasses import dataclass, field
from typing import Protocol


@dataclass(frozen=True)
class Letter:
    """Одно письмо заказчику.

    Все письма сервиса устроены одинаково: заголовок, несколько абзацев,
    одна кнопка с действием и приписка мелким шрифтом. Единая структура
    позволяет обойтись одним шаблоном оформления на все случаи и не даёт
    развести вёрстку по десятку копий.
    """

    subject: str
    """Тема. Попадает в список писем, поэтому пишется без воды."""

    heading: str
    paragraphs: tuple[str, ...]

    action_label: str = ""
    action_url: str = ""
    """Кнопка. Пустой адрес — письмо без действия, только уведомление."""

    footer: tuple[str, ...] = field(default_factory=tuple)
    """Приписка: что делать, если письмо пришло по ошибке, и срок ссылки."""


