#!/bin/sh
# Точка входа контейнера.
#
# Перед стартом приложения накатываются миграции. Приложение само таблицы
# не создаёт: иначе схема в базе и история миграций рано или поздно
# разойдутся, и обнаружится это в худший момент.
#
# RUN_MIGRATIONS=0 отключает этот шаг — например, когда миграции
# накатываются отдельным шагом деплоя.

set -e

if [ "${RUN_MIGRATIONS:-1}" = "1" ]; then
    echo "Применяю миграции..."
    alembic upgrade head
fi

exec "$@"
