"""Обратное чтение QR-кода — проверка того, что код действительно сканируется.

Без этой проверки тесты убеждались бы только в том, что пиксели нужного
цвета оказались на месте: картинка могла бы получаться красивой и при этом
нечитаемой. Особенно это важно для логотипа в центре, который перекрывает
часть модулей.

Два замечания про детектор:

* используется ``QRCodeDetectorAruco``, а не классический
  ``QRCodeDetector``: последний не справляется с кодами старших версий
  (от 14-й), которые получаются при уровне коррекции H, и давал бы
  ложные «код нечитаем»;
* OpenCV портит байты вне ASCII — кириллица возвращается искажённой,
  хотя сам код прочитан правильно. Поэтому на точное совпадение
  проверяются строки из ASCII, а для кириллических достаточно убедиться,
  что код вообще распознан и ASCII-части строки на месте.
"""

from io import BytesIO

import cv2
import numpy as np
from PIL import Image


def decode_qr(png: bytes) -> str | None:
    """Читает содержимое QR-кода из PNG.

    :return: раскодированная строка или None, если код прочитать не удалось.
    """
    with Image.open(BytesIO(png)) as image:
        # OpenCV работает с BGR, Pillow отдаёт RGB — отсюда разворот каналов.
        array = np.array(image.convert("RGB"))[:, :, ::-1]

    detector = cv2.QRCodeDetectorAruco()
    data, _, _ = detector.detectAndDecode(array)
    return data or None
